/**
 * Идентификатор нового блока.
 *
 * Ставим его на клиенте, а не ждём ответа сервера: к id привязаны ответы
 * гостей, голоса и треки, и блок должен быть узнаваем сразу — ещё до того,
 * как автосохранение доедет до бэка. Бэк проставит id сам, только если он
 * пришёл пустым.
 */
export function newBlockId(): string {
  if (typeof crypto !== 'undefined' && 'randomUUID' in crypto) {
    return crypto.randomUUID()
  }
  // Старые браузеры и SSR-окружения без Web Crypto: id всё равно нужен, а
  // уникальности в пределах одной страницы этого хватает.
  return `b-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`
}
